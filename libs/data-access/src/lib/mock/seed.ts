const DAY = 86_400_000;
const today = new Date();

function iso(daysFromNow: number): string {
  return new Date(today.getTime() + daysFromNow * DAY).toISOString().slice(0, 10);
}

function country(code: string): Country {
  const found = COUNTRIES.find((item) => item.code === code);
  if (!found) throw new Error(`Unknown country ${code}`);
  return found;
}

function coord(code: string, latOffset = 0, lngOffset = 0) {
  const c = country(code);
  return { lat: c.lat + latOffset, lng: c.lng + lngOffset };
}

