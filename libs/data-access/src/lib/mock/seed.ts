function makeProfile(input: {
  id: string;
  slug: string;
  name: string;
  avatar: string;
  headline: [string, string];
  bio: [string, string];
  city: string;
  countryCode: string;
  roles: readonly RoleId[];
  specialties: readonly SpecialtyId[];
  languages: readonly ProfileLanguage[];
  availability: Availability;
  verified: boolean;
  experience: readonly ExperienceItem[];
  education: readonly { id: string; title: [string, string]; institution: string; year: number }[];
  documents: readonly DocumentItem[];
  wishes: Wishlist;
  stats: { missions: number; countries: number; hours: number };
  joinedAt: string;
}): VolunteerProfile {
  const profile: VolunteerProfile = {
    id: input.id,
    slug: input.slug,
    name: input.name,
    avatar: input.avatar,
    headline: L(...input.headline),
    bio: L(...input.bio),
    location: { city: input.city, countryCode: input.countryCode },
    roles: input.roles,
    specialties: input.specialties,
    languages: input.languages,
    availability: input.availability,
    verified: input.verified,
    score: { total: 0, breakdown: { verification: 0, experience: 0, specialty: 0, languages: 0, recommendations: 0, missions: 0 } },
    experience: input.experience,
    education: input.education.map((item) => ({
      id: item.id,
      title: L(...item.title),
      institution: item.institution,
      year: item.year,
    })),
    documents: input.documents,
    wishes: input.wishes,
    stats: input.stats,
    joinedAt: input.joinedAt,
  };
  return profile;
}

