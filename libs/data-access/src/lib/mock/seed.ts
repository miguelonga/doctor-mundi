interface MissionInput {
  id: string;
  slug: string;
  titleEs: string;
  titleEn: string;
  orgId: string;
  summaryEs: string;
  summaryEn: string;
  descriptionEs: string;
  descriptionEn: string;
  roles: readonly RoleId[];
  specialties: readonly SpecialtyId[];
  urgency: Urgency;
  contractType: ContractType;
  countryCode: string;
  region: RegionId;
  city: string;
  startInDays: number;
  durationWeeks: number;
  filled: number;
  total: number;
  languages: readonly LanguageRequirement[];
  requirements: readonly [string, string][];
  responsibilities: readonly [string, string][];
  featured?: boolean;
  remote?: boolean;
  stipend?: [string, string];
}

function createMission(input: MissionInput): Mission {
  const startDate = iso(input.startInDays);
  const endDate = iso(input.startInDays + input.durationWeeks * 7);
  const seed = [...input.id].reduce((total, char) => total + char.charCodeAt(0), 0);
  const benefits = [
    L('Alojamiento compartido durante toda la misión', 'Shared accommodation for the whole mission'),
    L('Desplazamiento internacional cubierto', 'International travel covered'),
    L('Seguro médico y de evacuación', 'Medical and evacuation insurance'),
    L('Coordinación local y briefing de seguridad', 'Local coordination and security briefing'),
  ];
  if (input.stipend) {
    benefits.push(L(`Estipendio de ${input.stipend[0]}`, `Stipend of ${input.stipend[1]}`));
  }
  return {
    id: input.id,
    slug: input.slug,
    title: L(input.titleEs, input.titleEn),
    orgId: input.orgId,
    summary: L(input.summaryEs, input.summaryEn),
    description: L(input.descriptionEs, input.descriptionEn),
    roles: input.roles,
    specialties: input.specialties,
    urgency: input.urgency,
    status: input.filled >= input.total ? 'filled' : input.startInDays < 30 ? 'closing' : 'open',
    contractType: input.contractType,
    countryCode: input.countryCode,
    region: input.region,
    city: input.city,
    coordinates: coord(input.countryCode),
    startDate,
    endDate,
    durationWeeks: input.durationWeeks,
    slots: { total: input.total, filled: input.filled },
    languages: input.languages,
    requirements: input.requirements.map(([es, en]) => L(es, en)),
    responsibilities: input.responsibilities.map(([es, en]) => L(es, en)),
    benefits,
    logistics: {
      housing: true,
      travel: true,
      insurance: true,
      stipend: input.stipend ? L(input.stipend[0], input.stipend[1]) : undefined,
      notes: L(
        'El equipo local organiza el traslado desde el aeropuerto y la orientación en el terreno.',
        'The local team arranges airport pickup and field orientation.'
      ),
    },
    photos: [PHOTOS[seed % PHOTOS.length], PHOTOS[(seed + 3) % PHOTOS.length]],
    team: [TEAM[seed % TEAM.length], TEAM[(seed + 2) % TEAM.length]],
    createdAt: iso(-Math.abs(seed % 20) - 1),
    featured: input.featured ?? false,
    remote: input.remote ?? false,
  };
}

